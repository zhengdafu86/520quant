def get_sector_etf_by_industry(industry: str) -> str | None:
    """
    通过腾讯 API 返回的行业名称（vals[43]，申万分类）匹配对应 ETF。
    优先精确匹配，再做关键词模糊匹配（处理"XX制造"、"XX设备"等变体）。
    无匹配返回 None。
    """
    if not industry:
        return None
    # 精确匹配
    if industry in INDUSTRY_ETF_MAP:
        return INDUSTRY_ETF_MAP[industry]
    # 模糊匹配：industry 包含某个 key，或某个 key 包含在 industry 里
    for ind_key, etf_code in INDUSTRY_ETF_MAP.items():
        if ind_key in industry:
            return etf_code
    return None


def get_sector_etf(stock_name: str) -> str | None:
    """
    通过股票名称关键词匹配对应 ETF（兜底方案）。
    优先使用 get_sector_etf_by_industry()。
    """
    for keyword, etf_code in KEYWORD_ETF_MAP:
        if keyword in stock_name:
            return etf_code
    return None
